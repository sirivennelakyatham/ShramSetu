@router.post("/simulate-demo-reply/{request_id}")
def simulate_demo_reply(
    request_id: str,
    request: DemoReplyRequest,
):

    with get_db() as db:
        existing = db.execute(
            """
            SELECT request_id, status
            FROM ngo_requests
            WHERE request_id = ?
            """,
            (request_id,),
        ).fetchone()

        if not existing:
            raise HTTPException(
                status_code=404,
                detail="Request not found.",
            )

        if existing["status"] == "replied":
            raise HTTPException(
                status_code=409,
                detail="A reply has already been recorded for this request.",
            )

        replied_at = current_time()

        db.execute(
            """
            UPDATE ngo_requests
            SET status = ?,
                reply_text = ?,
                replied_at = ?
            WHERE request_id = ?
            """,
            (
                "replied",
                request.reply_text.strip(),
                replied_at,
                request_id,
            ),
        )
        db.commit()

    return {
        "success": True,
        "status": "replied",
        "request_id": request_id,
        "reply_received": True,
        "replied_at": replied_at,
        "message": (
            "A simulated demo reply has been saved. "
            "This was not an actual NGO response."
        ),
    }
