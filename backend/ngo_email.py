# --------------------------------------------------
# SAFE REPORT FORMATTING
# --------------------------------------------------

ALLOWED_REPORT_FIELDS = [
    "primary_category",
    "problem_description",
    "work_type",
    "employer_or_contractor",
    "work_location",
    "amount_owed",
    "duration",
    "incident_details",
    "immediate_danger",
    "injuries",
    "other_relevant_details",
]


def safe_value(value, not_provided="Not provided"):
    if value is None or value == "":
        return not_provided

    if isinstance(value, dict):
        return "; ".join(
            f"{key}: {safe_value(item, not_provided)}"
            for key, item in value.items()
        )[:2000]

    if isinstance(value, list):
        return "; ".join(
            safe_value(item, not_provided)
            for item in value
        )[:2000]

    return str(value).replace("\x00", "")[:2000]


def build_email_body(report, language="en"):
    text = EMAIL_TEXT.get(language, EMAIL_TEXT["en"])

    lines = [
        text["greeting"],
        "",
        text["intro"],
        "",
        text["details"],
        "------------------------------",
    ]

    for index, field in enumerate(ALLOWED_REPORT_FIELDS):
        if field in report:
            label = text["labels"][index]
            value = safe_value(
                report[field],
                text["not_provided"],
            )
            lines.append(f"{label}: {value}")

    lines.extend([
        "",
        text["footer"],
        "",
        text["regards"],
        "ShramSetu Demo Application",
    ])

    return "\n".join(lines)


