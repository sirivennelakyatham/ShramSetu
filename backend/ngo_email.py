@router.post("/send-demo-request")
def send_demo_request(request: DemoNGOEmailRequest):

    if request.consent_confirmed is not True:
        raise HTTPException(
            status_code=400,
            detail="Worker consent is required before sending.",
        )

    report = request.report

    if not isinstance(report, dict) or not report:
        raise HTTPException(
            status_code=400,
            detail="A valid grievance report is required.",
        )

    description = report.get("problem_description")

    if not isinstance(description, str) or not description.strip():
        raise HTTPException(
            status_code=400,
            detail="The grievance description is missing.",
        )

    language = request.language if request.language in EMAIL_TEXT else "en"

    request_id = str(uuid.uuid4())
    created_at = current_time()

    email = EmailMessage()

    email["Subject"] = (
        "ShramSetu demo - Request for worker assistance"
    )
    email["From"] = "shramsetu-demo@localhost"
    email["To"] = DEMO_NGO["email"]

    # Unique reference for future real email-thread integration.
    email["X-ShramSetu-Request-ID"] = request_id

    # Synthetic reply address for the local demo.
    email["Reply-To"] = (
        f"worker+{request_id}@shramsetu.local"
    )

    email.set_content(
        build_email_body(report, language)
    )

    try:
        with smtplib.SMTP(
            MAILPIT_HOST,
            MAILPIT_PORT,
            timeout=10,
        ) as smtp:
            smtp.send_message(email)

        with get_db() as db:
            db.execute(
                """
                INSERT INTO ngo_requests (
                    request_id,
                    organisation,
                    recipient,
                    status,
                    created_at,
                    language,
                    problem_description
                )
                VALUES (?, ?, ?, ?, ?, ?, ?)
                """,
                (
                    request_id,
                    DEMO_NGO["name"],
                    DEMO_NGO["email"],
                    "sent",
                    created_at,
                    language,
                    description[:2000],
                ),
            )
            db.commit()

        return {
            "success": True,
            "status": "captured_by_mailpit",
            "request_id": request_id,
            "organisation": DEMO_NGO["name"],
            "recipient": DEMO_NGO["email"],
            "message": (
                "The demo email was successfully captured "
                "by the local Mailpit inbox. "
                "It was not delivered to an external organisation."
            ),
        }

    except (OSError, smtplib.SMTPException) as error:
        print("MAILPIT EMAIL ERROR:", str(error))

        raise HTTPException(
            status_code=503,
            detail=(
                "Could not connect to the local email testing server. "
                "Make sure Mailpit is running."
            ),
        )


