const REPORT_KEYS = [
  "primary_category",
  "problem_description",
  "work_type",
  "employer_or_contractor",
  "work_location",
  "amount_owed",
  "duration",
  "incident_details",
  "immediate_danger",
  "injuries",
  "other_relevant_details"
];

function formatValue(value, notProvided) {
  if (value === null || value === undefined || value === "") {
    return notProvided;
  }

  if (typeof value === "object") {
    if (Array.isArray(value)) {
      return value
        .map((item) => formatValue(item, notProvided))
        .join("; ");
    }

    return Object.entries(value)
      .map(
        ([key, item]) =>
          `${key}: ${formatValue(item, notProvided)}`
      )
      .join("; ");
  }

  return String(value);
}

function NGOEmailRequest({ report, language = "en", onClose }) {
  const t = translations[language] || translations.en;

  const {
    speak,
    stopSpeech,
    speaking,
    loading: speechLoading,
    error: speechError,
  } = useSpeech(language);

  const [consent, setConsent] = useState(false);
  const [sending, setSending] = useState(false);
  const [error, setError] = useState("");
  const [success, setSuccess] = useState(false);
  const [requestId, setRequestId] = useState(null);
  const [reply, setReply] = useState(null);

  // Check for an organisation's reply after a request has an ID.
  useEffect(() => {
    if (!requestId || reply) return;

    let cancelled = false;

    const checkReply = async () => {
      try {
        const response = await fetch(
          `${API_URL}/ngo-email/request-status/${encodeURIComponent(requestId)}`
        );

        if (!response.ok || cancelled) return;

        const data = await response.json();

        if (!cancelled && data.reply_received) {
          setReply(data.reply_text);
        }
      } catch (error) {
        console.error("Reply check failed:", error);
      }
    };

    checkReply();

    const interval = setInterval(checkReply, 5000);

    return () => {
      cancelled = true;
      clearInterval(interval);
    };
  }, [requestId, reply]);

  const emailBody = useMemo(() => {
    const lines = [
      t.greeting,
      "",
      t.intro,
      "",
      t.details,
      "------------------------------"
    ];

    REPORT_KEYS.forEach((field, index) => {
      if (Object.prototype.hasOwnProperty.call(report || {}, field)) {
        lines.push(
          `${t.fields[index]}: ${formatValue(report[field], t.notProvided)}`
        );
      }
    });

    lines.push(
      "",
      t.footer,
      "",
      t.regards,
      t.app
    );

    return lines.join("\n");
  }, [report, t]);

  // Build the spoken text from THIS email dialog only.
  const getEmailScreenText = () => {
    if (success) {
      return [
        t.eyebrow,
        t.successTitle,
        t.successHeading,
        t.successText,
        requestId ? `Request ID: ${requestId}` : "",
        reply
          ? `Organisation replied: ${reply}`
          : "Waiting for a response.",
        t.return
      ].filter(Boolean).join("\n\n");
    }

    return [
      t.eyebrow,
      t.title,
      t.notice,
      `${t.to}: help@demo-ngo.test`,
      `${t.subject}: ${t.subjectText}`,
      t.preview,
      emailBody,
      t.consent,
      error
    ].filter(Boolean).join("\n\n");
  };

  const handleReadEmail = () => {
    if (speaking || speechLoading) {
      stopSpeech();
      return;
    }

    const text = getEmailScreenText();

    if (text.trim()) {
      speak(text);
    }
  };

  const handleClose = () => {
    stopSpeech();
    onClose();
  };

  const sendEmail = async () => {
    if (!consent || sending || success) return;

    setSending(true);
    setError("");

    try {
      const response = await fetch(`${API_URL}/ngo-email/send-demo-request`, {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify({
          consent_confirmed: true,
          report,
          language
        })
      });

      const data = await response.json().catch(() => ({}));

      if (!response.ok) {
        throw new Error(data.detail || t.error);
      }

      setRequestId(data.request_id);
      setSuccess(true);
    } catch (err) {
      setError(err.message || t.unavailable);
    } finally {
      setSending(false);
    }
  };

  return (
    <div className="ngo-email-overlay">
      <section
        className="ngo-email-dialog"
        role="dialog"
        aria-modal="true"
        aria-labelledby="ngo-email-title"
      >
        <header className="ngo-email-header">
          <div>
            <span className="ngo-email-eyebrow">{t.eyebrow}</span>
            <h2 id="ngo-email-title">
              {success ? t.successTitle : t.title}
            </h2>
          </div>

          <div style={{ display: "flex", alignItems: "center", gap: "8px" }}>
            <button
              type="button"
              className="ngo-email-close"
              onClick={handleReadEmail}
              aria-label={
                speaking || speechLoading ? t.stop : t.listen
              }
              title={
                speaking || speechLoading ? t.stop : t.listen
              }
              disabled={false}
            >
              {speechLoading ? (
                <LoaderCircle className="ngo-email-spinner" size={19} />
              ) : speaking ? (
                <Square size={19} />
              ) : (
                <Volume2 size={21} />
              )}
            </button>

            <button
              type="button"
              className="ngo-email-close"
              onClick={handleClose}
              aria-label="Close"
              disabled={sending}
            >
              <X size={21} />
            </button>
          </div>
        </header>

        {speechError && (
          <p className="ngo-email-error" role="alert">
            {speechError}
          </p>
        )}

        {success ? (
          <div className="ngo-email-success">
            <CheckCircle size={52} />

            <h3>{t.successHeading}</h3>
            <p>{t.successText}</p>

            {requestId && (
              <p>
                Request ID: <strong>{requestId}</strong>
              </p>
            )}

            {reply ? (
              <div className="ngo-reply-notification">
                <h3>Organisation replied</h3>
                <p>{reply}</p>
              </div>
            ) : (
              <p>Waiting for a response...</p>
            )}

            <button type="button" onClick={handleClose}>
              {t.return}
            </button>
          </div>
        ) : (
          <>
            <div className="ngo-email-demo-notice">
              <ShieldAlert size={19} />
              <p>{t.notice}</p>
            </div>

            <div className="ngo-email-preview">
              <div className="ngo-email-meta">
                <span>{t.to}</span>
                <strong>help@demo-ngo.test</strong>
              </div>

              <div className="ngo-email-meta">
                <span>{t.subject}</span>
                <strong>{t.subjectText}</strong>
              </div>

              <div className="ngo-email-body">
                <span>{t.preview}</span>
                <pre>{emailBody}</pre>
              </div>
            </div>

            <label className="ngo-email-consent">
              <input
                type="checkbox"
                checked={consent}
                onChange={(event) => setConsent(event.target.checked)}
              />
              <span>{t.consent}</span>
            </label>

            {error && (
              <p className="ngo-email-error" role="alert">
                {error}
              </p>
            )}

            <div className="ngo-email-actions">
              <button
                type="button"
                className="ngo-email-cancel"
                onClick={handleClose}
                disabled={sending}
              >
                {t.cancel}
              </button>

              <button
                type="button"
                className="ngo-email-send"
                onClick={sendEmail}
                disabled={!consent || sending}
              >
                {sending ? (
                  <LoaderCircle className="ngo-email-spinner" size={18} />
                ) : (
                  <Send size={18} />
                )}
                {sending ? t.sending : t.send}
              </button>
            </div>
          </>
        )}
      </section>
    </div>
  );
}

export default NGOEmailRequest;
