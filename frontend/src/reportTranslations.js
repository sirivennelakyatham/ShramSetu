export function getReportQuestionText(language, question) {
  return (
    reportTranslations[language]?.questions?.[question.id] ||
    reportTranslations.en.questions[question.id] ||
    question.text
  );
}

export function getReportOptionText(language, option) {
  const value =
    typeof option === "object"
      ? option.value ?? option.label
      : option;

  return (
    reportTranslations[language]?.options?.[value] ||
    reportTranslations.en.options[value] ||
    (typeof option === "object"
      ? option.label ?? option.value
      : option)
  );
}

export function getReportLabel(language, key) {
  return (
    reportTranslations[language]?.labels?.[key] ||
    reportTranslations.en.labels[key] ||
    key
  );
}
