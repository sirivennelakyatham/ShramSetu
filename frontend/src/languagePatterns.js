// =====================================================
// 5. LOOK UP AN INDIVIDUAL NUMBER WORD
// This does not yet combine words such as "two hundred".
// That will be handled by the number parser.
// =====================================================

export function getNumberValue(word, language = "en") {
  const normalized = normalizeText(word);
  const dictionary = NUMBER_WORDS[language];

  if (!dictionary) {
    return null;
  }

  if (Object.prototype.hasOwnProperty.call(dictionary, normalized)) {
    return dictionary[normalized];
  }

  return null;
}