// =====================================================
// 1. NORMALISATION
// =====================================================

export function normalizeText(text) {
  return String(text || "")
    .normalize("NFC")
    .toLowerCase()
    .trim()
    .replace(/[.,!?;:।॥]/g, "")
    .replace(/\s+/g, " ");
}


