// =====================================================
// 3. RECOGNISE A STRUCTURED ANSWER
// =====================================================

export function recogniseAnswer(text, language = "en") {
  const normalized = normalizeText(text);
  const dictionary = ANSWER_WORDS[language];

  if (!dictionary || !normalized) {
    return null;
  }

  for (const [answerType, words] of Object.entries(dictionary)) {
    const match = words.some(
      word => normalizeText(word) === normalized
    );

    if (match) {
      return answerType;
    }
  }

  return null;
}


